#!/usr/bin/env node
/* ============================================================
   statistics.mjs — the authoritative source for every count in the
   documentation.

   The README and docs/AGENT-RESOURCES.md used to carry hand-maintained
   numbers that drifted from the build (six resources vs nine, a stale
   advisory count, a point-in-time article count). This script reads the
   build artifacts and the committed validation reports and regenerates
   docs/STATISTICS.md. Every number in the prose docs should come from
   here, not from a hand edit.

   Usage:
     node scripts/statistics.mjs        # writes docs/STATISTICS.md
   ============================================================ */

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const APP = path.join(root, ".next", "server", "app");
const OUT = path.join(root, "docs", "STATISTICS.md");

const RESOURCES = [
  { path: "/llms.txt", type: "text/plain" },
  { path: "/llms-full.txt", type: "text/plain" },
  { path: "/agents/index.json", type: "application/json" },
  { path: "/agents/catalog.json", type: "application/json" },
  { path: "/agents/graph.json", type: "application/json" },
  { path: "/agents/book.json", type: "application/json" },
  { path: "/agents/claims.json", type: "application/json" },
  { path: "/agents/evidence.json", type: "application/json" },
  { path: "/agents/proposals.json", type: "application/json" },
];

const readBody = (urlPath) => {
  const file = path.join(APP, `${urlPath.replace(/^\//, "")}.body`);
  return fs.existsSync(file) ? fs.readFileSync(file) : null;
};

const sha = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
const json = (buf) => JSON.parse(buf.toString("utf8"));

function gitCommit() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], { cwd: root }).toString().trim().slice(0, 12);
  } catch {
    return "unknown";
  }
}

function main() {
  if (!fs.existsSync(APP)) {
    console.error(`❌ no build at ${path.relative(root, APP)} — run \`npm run build\` first`);
    process.exit(1);
  }

  const catalog = json(readBody("/agents/catalog.json"));
  const graph = json(readBody("/agents/graph.json"));
  const claims = json(readBody("/agents/claims.json"));
  const evidence = json(readBody("/agents/evidence.json"));
  const proposals = json(readBody("/agents/proposals.json"));
  const index = json(readBody("/agents/index.json"));

  const audit = fs.existsSync(path.join(root, "data", "audit-report.json"))
    ? JSON.parse(fs.readFileSync(path.join(root, "data", "audit-report.json"), "utf8"))
    : null;
  const conformance = fs.existsSync(path.join(root, "data", "conformance-report.json"))
    ? JSON.parse(fs.readFileSync(path.join(root, "data", "conformance-report.json"), "utf8"))
    : null;

  const mirrors = fs
    .readdirSync(path.join(APP, "research"), { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".md.body"))
    .length;

  const posts = audit?.counts?.posts ?? catalog.articles.length;
  const drafts = audit?.counts?.drafts ?? 0;
  const published = audit?.counts?.published ?? catalog.articles.length;

  const lines = [];
  lines.push("# Corpus statistics");
  lines.push("");
  lines.push("**Generated by `scripts/statistics.mjs` from the build artifacts. Do not edit.**");
  lines.push("");
  lines.push("## Corpus");
  lines.push("");
  lines.push("| Count | Value |");
  lines.push("|---|---|");
  lines.push(`| Source files | ${posts} |`);
  lines.push(`| Published articles | ${published} |`);
  lines.push(`| Drafts (excluded) | ${drafts} |`);
  lines.push(`| Projects | ${catalog.projects.length} |`);
  lines.push(`| Concepts | ${catalog.concepts.length} |`);
  lines.push(`| Learning paths | ${catalog.paths.length} |`);
  lines.push(`| Book chapters | ${catalog.chapters.length} |`);
  lines.push(`| Graph edges | ${Object.values(graph.counts).reduce((a, b) => a + b, 0)} |`);
  lines.push(`| Claims | ${claims.claims.length} |`);
  lines.push(`| Evidence records | ${evidence.evidence.length} |`);
  lines.push(`| Non-authoritative proposals | ${proposals.proposals.length} |`);
  lines.push(`| Markdown mirrors | ${mirrors} |`);
  lines.push("");
  lines.push("## Relation graph by type");
  lines.push("");
  lines.push("| Relation | Edges |");
  lines.push("|---|---|");
  for (const [type, count] of Object.entries(graph.counts).sort((a, b) => b[1] - a[1])) {
    lines.push(`| \`${type}\` | ${count} |`);
  }
  lines.push("");
  lines.push("## Machine-readable resources");
  lines.push("");
  lines.push("| Path | Type | Bytes | sha256 (first 12) |");
  lines.push("|---|---|---|---|");
  for (const r of RESOURCES) {
    const body = readBody(r.path);
    if (!body) {
      lines.push(`| \`${r.path}\` | ${r.type} | — | — |`);
      continue;
    }
    lines.push(`| \`${r.path}\` | ${r.type} | ${body.length} | \`${sha(body).slice(0, 12)}\` |`);
  }
  lines.push("");
  lines.push(
    `The master index (\`/agents/index.json\`) lists ${index.resources.length} resources and reports ${kb(
      index.resources.reduce((n, r) => n + r.bytes, 0)
    )} in total.`
  );
  lines.push("");
  lines.push("## Validation");
  lines.push("");
  lines.push("| Gate | Result |");
  lines.push("|---|---|");
  if (conformance) {
    lines.push(
      `| Corpus conformance | ${conformance.summary.errors} error(s), ${conformance.summary.warnings} warning(s), ${conformance.summary.info} info |`
    );
  }
  if (audit) {
    lines.push(
      `| Content audit | ${audit.counts.fatal ?? 0} fatal, ${audit.counts.defect ?? 0} defect, ${audit.counts.advisory ?? 0} advisory |`
    );
  }
  lines.push("");
  lines.push("## Notes");
  lines.push("");
  lines.push(
    "- The article count is **published** articles: source files minus drafts. Drafts never reach the pages, sitemap, feed, catalog, route manifest or agent corpus."
  );
  lines.push(
    "- The nine machine-readable resources are the rows above. `/agents` (HTML) and `/research/{slug}.md` (Markdown mirrors) are additional surfaces, not separate resources."
  );
  lines.push(
    "- Every figure above is read from the build output or the committed validation reports; none is hand-maintained."
  );
  lines.push("");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"));
  console.log(`statistics: ${path.relative(root, OUT)} — ${published} articles, ${RESOURCES.length} resources, ${mirrors} mirrors`);
}

main();
